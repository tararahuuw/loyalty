import React, { useRef, Fragment, useState, useEffect } from "react";
import { Dialog, Transition } from "@headlessui/react";
import {
  OutlineButton,
  PrimaryButton,
  TextInput,
  ModalResult,
  ModalState,
  TextArea,
  Switch,
} from "sprint-asia-custom-component";
import { Camera, UploadSimple, X, Copy, Info } from "@phosphor-icons/react";
import LoadingModal from "prezent/LoadingModal";
import { useDisclosure } from "prezent/useDisclosure";
import { useFormik } from "formik";
import * as yup from "yup";
import { CreateLoyalty, EditLoyalty } from "../../../service/programmanagement/endpoint";

const MyLoyaltyFormModal = ({ isOpen, onOpen, onClose, setSelectedLoyalty, selectedLoyalty, refetch }) => {
  const cancelButtonRef = useRef(null);
  const inputLogoRef = useRef(null);
  const [flagResult, setFlagResult] = useState("success");
  const [dataSubtitleModal, setDataSubtitleModal] = useState("");
  const [isModalOpenResult, setIsModalOpenResult] = useState(false);
  const { isOpen: loadingModalIsOpen, open: openLoading, close: closeLoading } = useDisclosure();
  const { isOpen: confirmationModalIsOpen, toggle: toggleConfirmationModal } = useDisclosure(false);

  const handleLogoChange = (event) => {
    const file = event.target.files[0];
    formik.setFieldTouched("logo", true, false);
    formik.setFieldValue("logo", file);
  };

  function handleOpenModalResult(type, subtitle) {
    setTimeout(() => {
      setFlagResult(type);
      setDataSubtitleModal(subtitle);
      setIsModalOpenResult(true);
      setTimeout(() => {
        setIsModalOpenResult(false);
      }, 1500);
    }, 250);
  }

  const formik = useFormik({
    enableReinitialize: true,
    initialValues: {
      projectName: selectedLoyalty?.projectName || "",
      description: selectedLoyalty?.description || "",
      logo: selectedLoyalty?.logoURL || "",
      landingPageURL: selectedLoyalty?.landingPageURL || "",
      isAutoGenerated: selectedLoyalty?.isAutoGenerated || false,
      onFocus: true,
    },
    validationSchema: yup.object().shape({
      projectName: yup.string().required("Please complete this required field to continue"),
      logo: yup
        .mixed()
        .required("required")
        .test("fileOrUrl", "invalid_format", (value) => {
          if (!value) return false;
          if (typeof value === "string") {
            try {
              new URL(value);
              return true;
            } catch {
              const ext = value.split(".").pop().toLowerCase();
              return ["png", "jpeg", "jpg"].includes(ext);
            }
          }
          if (value && value.type) {
            const supportedFormats = ["image/png", "image/jpeg", "image/jpg"];
            return supportedFormats.includes(value.type);
          }
          return false;
        }),
      landingPageURL: yup.string().required("Please complete this required field to continue"),
    }),
    validateOnChange: true,
    validateOnBlur: true,
    onSubmit: (values) => {
      const formData = new FormData();
      if (selectedLoyalty?.id) {
        formData.append("id", selectedLoyalty.id);
      }

      for (let key in values) {
        if (key === "logo") {
          if (typeof values[key] !== "string") {
            formData.append(key, values[key]);
          }
        } else {
          formData.append(key, values[key]);
        }
      }
      handleSubmitLoyalty(formData);
    },
  });

  const handleCloseModal = () => {
    if (formik.dirty) {
      onClose();
      toggleConfirmationModal();
    } else {
      formik.resetForm();
      setSelectedLoyalty(null);
      onClose();
    }
  };

  const handleSubmitLoyalty = async (form) => {
    try {
      onClose();
      openLoading();
      if (selectedLoyalty) {
        await EditLoyalty(form);
      } else {
        await CreateLoyalty(form);
      }
      refetch();
      formik.resetForm();
      setSelectedLoyalty(null);
      closeLoading();
      setTimeout(() => {
        handleOpenModalResult("success", `Program has been successfully ${selectedLoyalty ? "updated" : "added"}.`);
      }, 250);
    } catch (error) {
      closeLoading();
      if (error?.response?.data?.rc === 409) {
        onOpen();
        formik.setFieldError(
          "landingPageURL",
          "Lading Page URL already exist. Please enter a unique value to continue."
        );
        formik.setFieldError("projectName", "Program name is already exists. Please enter a unique value to continue.");
      } else {
        handleOpenModalResult("failed", `Failed to ${selectedLoyalty ? "update" : "add"} program. Please try again.`);
        formik.resetForm();
        setSelectedLoyalty(null);
      }
    }
  };

  useEffect(() => {
    if (formik.values.isAutoGenerated) {
      formik.setFieldValue("landingPageURL", formik.values.projectName.toLowerCase().trim().replace(/\s+/g, "_"));
    }
  }, [formik.values.projectName, formik.values.isAutoGenerated]);

  return (
    <>
      <Transition.Root show={isOpen} as={Fragment}>
        <Dialog
          as="div"
          className="fixed inset-0 overflow-y-auto z-50"
          initialFocus={cancelButtonRef}
          onClose={() => {}}
          static={false}
          style={{ zIndex: 1001 }}
        >
          <Transition.Child
            as={Fragment}
            enter="ease-out duration-300"
            enterFrom="opacity-0"
            enterTo="opacity-100"
            leave="ease-in duration-200"
            leaveFrom="opacity-100"
            leaveTo="opacity-0"
          >
            <div className="fixed inset-0 bg-black bg-opacity-25" onClick={(e) => e.stopPropagation()} />
          </Transition.Child>

          <Transition.Child
            as={Fragment}
            enter="ease-out duration-300"
            enterFrom="opacity-0 translate-y-4 sm:translate-y-0 sm:scale-95"
            enterTo="opacity-100 translate-y-0 sm:scale-100"
            leave="ease-in duration-200"
            leaveFrom="opacity-100 translate-y-0 sm:scale-100"
            leaveTo="opacity-0 translate-y-4 sm:translate-y-0 sm:scale-95"
          >
            <div className="min-h-screen flex items-center justify-center">
              <Dialog.Panel className="relative w-full max-w-lg bg-white rounded-lg shadow-xl transition-all sm:my-8 sm:w-full sm:max-w-2xl py-3 flex flex-col">
                <div className="flex justify-between px-8 py-2">
                  <p className="font-semibold text-xl text-black">
                    {selectedLoyalty ? "Edit Program" : "Create New Loyalty Program"}
                  </p>
                  <div className="cursor-pointer" onClick={handleCloseModal}>
                    <X size={24} />
                  </div>
                </div>
                <div className="border-t border-neutral30 flex flex-col gap-4 px-8 py-4">
                  <p>
                    Please create a new loyalty program with custom branding. A landing page will be automatically
                    generated to support customer engagement.
                  </p>

                  <TextInput
                    title="Program Name"
                    isRequired={true}
                    placeholder="Input Program Name"
                    value={formik.values.projectName}
                    onChangeInput={(e) => {
                      let value = e.target.value;

                      // hanya izinkan huruf, angka, spasi, underscore, dan strip
                      value = value.replace(/[^a-zA-Z0-9 _-]/g, "");

                      // batasi panjang maksimal 30
                      value = value.slice(0, 30);

                      formik.setFieldValue("projectName", value);
                      formik.setFieldTouched("projectName", true, false);
                    }}
                    footer={
                      (formik.touched.projectName || formik.submitCount > 0) && formik.errors.projectName
                        ? formik.errors.projectName
                        : null
                    }
                    mode={
                      (formik.touched.projectName || formik.submitCount > 0) && formik.errors.projectName
                        ? "danger"
                        : "default"
                    }
                  />

                  <TextArea
                    title="Description"
                    isRequired={false}
                    placeholder="Input Description"
                    value={formik.values.description}
                    onChangeInput={(e) => {
                      formik.setFieldValue("description", e.target.value);
                      formik.setFieldTouched("description", true, false);
                    }}
                    footer={
                      (formik.touched.description || formik.submitCount > 0) && formik.errors.description
                        ? formik.errors.description
                        : null
                    }
                    mode={
                      (formik.touched.description || formik.submitCount > 0) && formik.errors.description
                        ? "danger"
                        : "default"
                    }
                  />

                  <div>
                    <p>
                      Program Logo <span className="text-danger500">*</span>
                    </p>
                    <div className="flex items-center gap-4 mt-2 flex-shrink-0">
                      {formik.values.logo && formik.errors.logo !== "invalid_format" ? (
                        <img
                          src={
                            typeof formik.values.logo === "string"
                              ? formik.values.logo
                              : URL.createObjectURL(formik.values.logo)
                          }
                          className={`flex-shrink-0 w-20 h-20 object-fill rounded-md border border-neutral80 cursor-pointer`}
                          onClick={() => inputLogoRef.current.click()}
                        />
                      ) : (
                        <div
                          className={`flex-shrink-0 border border-dashed border-neutral80 rounded-md w-20 h-20 flex items-center justify-center cursor-pointer`}
                          onClick={() => inputLogoRef.current.click()}
                        >
                          <Camera size={30} className="text-neutral300" />
                        </div>
                      )}

                      <div className="flex flex-col gap-1">
                        <div className="flex items-center gap-3">
                          <a
                            className={`cursor-pointer border rounded-md ${
                              (formik.touched.logo || formik.submitCount > 0) && formik.errors.logo
                                ? "bg-danger50 border-danger500 w-full"
                                : "bg-white border-neutral80"
                            } py-2 px-4 flex items-center justify-between gap-1`}
                            onClick={() => inputLogoRef.current.click()}
                          >
                            <div className="flex items-center">
                              <UploadSimple />
                              <span className="px-2">Upload Logo</span>
                            </div>
                            {formik.values.logo && (
                              <a
                                className="cursor-pointer whitespace-nowrap ml-2"
                                onClick={() => formik.setFieldValue("logo", "")}
                              >
                                x
                              </a>
                            )}
                          </a>
                        </div>

                        {formik.touched.logo || formik.submitCount > 0 ? (
                          formik.errors.logo === "required" ? (
                            <div className="flex items-start text-sm">
                              <Info className="text-danger500 mr-2 mt-0.5" size={16} />
                              <p className="text-danger500 flex-1">
                                Please complete this required field to continue. Supported formats: PNG, JPEG, JPG
                                (recommended size: 128 × 128 px).
                              </p>
                            </div>
                          ) : formik.errors.logo === "invalid_format" ? (
                            <div className="flex items-start text-sm">
                              <Info className="text-danger500 mr-2 mt-0.5" size={16} />
                              <p className="text-danger500 flex-1">
                                Invalid file format or size. Please upload a PNG, JPEG, or JPG file with the recommended
                                size of 128 × 128 px.
                              </p>
                            </div>
                          ) : (
                            <p className="text-sm text-neutral500">
                              Supported formats: PNG, JPEG, JPG (recommended size: 128 x 128 px).
                            </p>
                          )
                        ) : (
                          <p className="text-sm text-neutral500">
                            Supported formats: PNG, JPEG, JPG (recommended size: 128 x 128 px).
                          </p>
                        )}
                      </div>
                    </div>
                  </div>
                  <div>
                    <div className="flex items-center mb-2">
                      <p className="font-semibold mr-2">Auto-Generated Landing Page URL</p>
                      <Switch
                        checked={formik.values.isAutoGenerated}
                        onChange={() => formik.setFieldValue("isAutoGenerated", !formik.values.isAutoGenerated)}
                        isEdit={true}
                      />
                    </div>

                    <div
                      className={`${
                        (formik.touched.landingPageURL || formik.submitCount > 0) && formik.errors.landingPageURL
                          ? "bg-danger50 border border-danger500 text-neutral300"
                          : "bg-primary50 text-primary500"
                      } p-2 rounded-md`}
                    >
                      {formik.values.isAutoGenerated ? (
                        <div className="flex justify-between items-center">
                          <p className="break-all">
                            {`https://stagpwa-prezent.sandeza.id/${formik.values.landingPageURL}`}
                          </p>
                          {(formik.touched.landingPageURL || formik.submitCount > 0) && formik.errors.landingPageURL ? (
                            <Info size={20} className="text-danger500" />
                          ) : (
                            <button
                              type="button"
                              onClick={() =>
                                navigator.clipboard.writeText(
                                  `https://stagpwa-prezent.sandeza.id/${formik.values.landingPageURL}`
                                )
                              }
                              className="mt-1 px-2 self-start text-neutral500 hover:text-primary500"
                            >
                              <Copy size={20} weight="regular" />
                            </button>
                          )}
                        </div>
                      ) : (
                        <>
                          {formik.values.onFocus || !formik.values.landingPageURL ? (
                            <div className="flex justify-between items-center">
                              <div className="flex items-center">
                                <p>{`https://stagpwa-prezent.sandeza.id/`}</p>
                                <input
                                  autoFocus
                                  value={formik.values.landingPageURL}
                                  placeholder="program_name"
                                  onFocus={() => formik.setFieldValue("onFocus", true)}
                                  onBlur={() => {
                                    if (formik.values.landingPageURL) {
                                      formik.setFieldValue("onFocus", false);
                                    }
                                  }}
                                  onChange={(e) => {
                                    let value = e.target.value;

                                    // hanya izinkan huruf, angka, spasi, underscore, strip
                                    value = value.replace(/[^a-zA-Z0-9 _-]/g, "");

                                    // ubah ke lowercase
                                    value = value.toLowerCase();

                                    // ganti semua spasi jadi underscore
                                    value = value.replace(/\s+/g, "_");

                                    // rapikan underscore berlebih
                                    value = value.replace(/_+/g, "_");

                                    // batasi maksimal 30 karakter
                                    value = value.slice(0, 30);

                                    formik.setFieldValue("landingPageURL", value);
                                    formik.setFieldTouched("landingPageURL", true, false);
                                  }}
                                  className={`${
                                    (formik.touched.landingPageURL || formik.submitCount > 0) &&
                                    formik.errors.landingPageURL
                                      ? "bg-danger50 text-neutral300 "
                                      : "bg-primary50 text-primary500"
                                  }`}
                                />
                              </div>
                              {(formik.touched.landingPageURL || formik.submitCount > 0) &&
                              formik.errors.landingPageURL ? (
                                <Info size={20} className="text-danger500" />
                              ) : (
                                <button
                                  type="button"
                                  onClick={() =>
                                    navigator.clipboard.writeText(
                                      `https://stagpwa-prezent.sandeza.id/${formik.values.landingPageURL}`
                                    )
                                  }
                                  className="mt-1 px-2 self-start text-neutral500 hover:text-primary500"
                                >
                                  <Copy size={20} weight="regular" />
                                </button>
                              )}
                            </div>
                          ) : (
                            <div className="flex justify-between items-center">
                              <p
                                onClick={() => formik.setFieldValue("onFocus", true)}
                                className="cursor-pointer break-all"
                              >
                                {`https://stagpwa-prezent.sandeza.id/${formik.values.landingPageURL}`}
                              </p>
                              <button
                                type="button"
                                onClick={() =>
                                  navigator.clipboard.writeText(
                                    `https://stagpwa-prezent.sandeza.id/${formik.values.landingPageURL}`
                                  )
                                }
                                className="mt-1 px-2 self-start text-neutral500 hover:text-primary500"
                              >
                                <Copy size={20} weight="regular" />
                              </button>
                            </div>
                          )}
                        </>
                      )}
                    </div>

                    <div className="mt-2">
                      {(formik.touched.landingPageURL || formik.submitCount > 0) && formik.errors.landingPageURL && (
                        <div className="flex items-center text-sm">
                          <Info className="text-danger500 mr-2" size={16} />
                          <p className="text-danger500">{formik.errors.landingPageURL}</p>
                        </div>
                      )}
                      {formik.errors.landingPageURL !== "Please complete this required field to continue" && (
                        <p className={`text-neutral300 text-sm`}>
                          The landing page URL is generated automatically using the program name and can be used for
                          customer registration. Turn the toggle off to deactivate this feature.
                        </p>
                      )}
                    </div>
                  </div>

                  <input
                    ref={inputLogoRef}
                    type="file"
                    accept="image/png, image/jpeg"
                    className="hidden"
                    onChange={handleLogoChange}
                  />
                </div>

                <div className="border-t border-neutral30 flex items-center gap-4 justify-end px-8 py-3">
                  <OutlineButton title="Cancel" onClick={handleCloseModal} />
                  <PrimaryButton title={"Submit"} onClick={formik.handleSubmit} />
                </div>
              </Dialog.Panel>
            </div>
          </Transition.Child>
        </Dialog>
      </Transition.Root>
      <LoadingModal title="Loading..." subtitle="Please wait a moment" isOpen={loadingModalIsOpen} onClose={() => {}} />
      <ModalResult subtitle={dataSubtitleModal} type={flagResult} isOpen={isModalOpenResult} />
      <ModalState
        title="Do you want to cancel?"
        subtitle="The information you filled in has not been saved and will be lost if you cancel this process."
        isOpen={confirmationModalIsOpen}
        onClose={() => {
          onOpen();
          toggleConfirmationModal();
        }}
        type="default"
        titleButtonLeft="Back"
        titleButtonRight="Cancel"
        leftAction={() => {
          onOpen();
          toggleConfirmationModal();
        }}
        rightAction={() => {
          toggleConfirmationModal();
          formik.resetForm();
          setSelectedLoyalty(null);
        }}
      />
    </>
  );
};

export default MyLoyaltyFormModal;
