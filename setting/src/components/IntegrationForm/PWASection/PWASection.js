import React, { useRef, useEffect } from "react";
import { PrimaryButton, TextInput, TextArea, Switch, OutlineButton, Chip } from "sprint-asia-custom-component";
import { Camera, Copy, Info, CaretDown, NotePencil, X } from "@phosphor-icons/react";
import { useDisclosure } from "prezent/useDisclosure";
import { useFormik } from "formik";
import * as yup from "yup";
import ToolTip from "prezent/ToolTip";
import DangerButton from "prezent/DangerButton";

const PWASection = ({ selectedLoyalty, handleSubmitPWA }) => {
  const contentRef = useRef(null);
  const inputLogoRef = useRef(null);
  const { isOpen: editMode, toggle: toggleEdit } = useDisclosure();
  const { isOpen: formIsOpen, toggle: toggleForm } = useDisclosure(true);

  const handleLogoChange = (event) => {
    const file = event.target.files[0];
    formik.setFieldTouched("logo", true, false);
    formik.setFieldValue("logo", file);
  };

  const formik = useFormik({
    enableReinitialize: true,
    initialValues: {
      projectName: selectedLoyalty?.projectName || "",
      description: selectedLoyalty?.description || "",
      logo: selectedLoyalty?.logoURL || "",
      landingPageURL: selectedLoyalty?.landingPageURL || "",
      isAutoGenerated: selectedLoyalty?.isAutoGenerated ?? true,
      status: selectedLoyalty?.status || false,
      onFocus: true,
    },
    validationSchema: yup.object().shape({
      projectName: yup.string().required("Please complete this required field to continue"),
      logo: yup
        .mixed()
        .required("required")
        .test("fileOrUrl", "invalid_format", (value) => {
          if (!value) return false;
          if (typeof value === "string") {
            try {
              new URL(value);
              return true;
            } catch {
              const ext = value.split(".").pop().toLowerCase();
              return ["png", "jpeg", "jpg"].includes(ext);
            }
          }
          if (value && value.type) {
            const supportedFormats = ["image/png", "image/jpeg", "image/jpg"];
            return supportedFormats.includes(value.type);
          }
          return false;
        }),
      landingPageURL: yup.string().required("Please complete this required field to continue"),
    }),
    validateOnChange: true,
    validateOnBlur: true,
    onSubmit: (values) => {
      const formData = new FormData();
      if (selectedLoyalty?.id) {
        formData.append("id", selectedLoyalty.id);
      }

      for (let key in values) {
        if (key === "logo") {
          if (typeof values[key] !== "string") {
            formData.append(key, values[key]);
          }
        } else {
          formData.append(key, values[key]);
        }
      }
      handleSubmitPWA(formData, toggleEdit);
    },
  });

  useEffect(() => {
    if (formik.values.isAutoGenerated) {
      formik.setFieldValue("landingPageURL", formik.values.projectName.toLowerCase().trim().replace(/\s+/g, "_"));
    }
  }, [formik.values.projectName, formik.values.isAutoGenerated]);

  return (
    <div className="flex flex-col gap-3 bg-white rounded-lg border border-neutral40 shadow-md p-6">
      <div className="flex flex-col gap-2 pb-2 border-b border-neutral40">
        <div className="flex justify-between items-center">
          <div className="flex flex-col w-full">
            <div className="flex items-center gap-2">
              <p className="text-lg font-semibold leading-6 text-left">PWA</p>

              <ToolTip
                message="PWA (Progressive Web App) allows you to create a loyalty program with custom branding accessible via a dedicated web application. A landing page will be automatically generated to support customer engagement."
                id="pwa"
              />

              {editMode ? (
                <Switch
                  checked={formik.values.status}
                  isEdit
                  onChange={() => formik.setFieldValue("status", !formik.values.status)}
                />
              ) : (
                <div>
                  <Chip
                    type={formik.values.status ? "success" : "neutral"}
                    title={formik.values.status ? "Active" : "Inactive"}
                  />
                </div>
              )}
            </div>

            <p className="text-sm text-neutral300 whitespace-pre-line">
              {`Build your own branded loyalty mini app with PWA!\nProvide a smooth, app-like experience where customers can join, earn, and redeem rewards instantly—all in one link.`}
            </p>
          </div>

          <a className="cursor-pointer" onClick={toggleForm}>
            <CaretDown
              className={`transform ${
                formIsOpen ? "rotate-180" : "rotate-0"
              } transition-transform duration-300 ease-in-out`}
            />
          </a>
        </div>
      </div>

      <div
        ref={contentRef}
        style={{
          maxHeight: !formIsOpen ? 0 : 2000,
        }}
        className="flex flex-col gap-4 overflow-hidden transition-[max-height] duration-300"
      >
        <div className="grid grid-cols-5 gap-8">
          {editMode ? (
            <>
              <div className="flex flex-col gap-4">
                {formik.values.logo && formik.errors.logo !== "invalid_format" ? (
                  <div className="relative">
                    <X
                      className="text-black absolute right-0 cursor-pointer"
                      size={20}
                      onClick={() => formik.setFieldValue("logo", "")}
                    />
                    <img
                      src={
                        typeof formik.values.logo === "string"
                          ? formik.values.logo
                          : URL.createObjectURL(formik.values.logo)
                      }
                      className={`object-contain rounded-md border border-neutral80 cursor-pointer h-44`}
                      onClick={() => inputLogoRef.current.click()}
                    />
                  </div>
                ) : (
                  <div
                    className={`border ${
                      formik.touched.logo || formik.submitCount > 0
                        ? "border-danger500 bg-danger50"
                        : "border-neutral80 bg-white"
                    } items-center justify-center cursor-pointer rounded-md overflow-hidden`}
                  >
                    <div
                      className="flex items-center justify-center rounded-t-md h-44"
                      onClick={() => inputLogoRef.current.click()}
                    >
                      <Camera
                        size={50}
                        className={`${
                          formik.touched.logo || formik.submitCount > 0 ? "text-danger500" : "text-neutral300"
                        }`}
                      />
                    </div>

                    <div
                      className={`${
                        formik.touched.logo || formik.submitCount > 0
                          ? "bg-danger50 text-danger500 border-danger500"
                          : "bg-primary50 text-primary500 border-neutral80"
                      } px-4 py-2 flex justify-center border-t`}
                    >
                      Upload Logo
                    </div>
                  </div>
                )}

                <div className="flex flex-col gap-1">
                  {formik.touched.logo || formik.submitCount > 0 ? (
                    formik.errors.logo === "required" ? (
                      <div className="flex items-start text-sm">
                        <Info className="text-danger500 mr-2 mt-0.5" size={16} />
                        <p className="text-danger500 text-xs flex-1">
                          Please complete this required field to continue. Supported formats: PNG, JPEG, JPG
                          (recommended size: 128 × 128 px).
                        </p>
                      </div>
                    ) : formik.errors.logo === "invalid_format" ? (
                      <div className="flex items-start text-sm">
                        <Info className="text-danger500 mr-2 mt-0.5" size={16} />
                        <p className="text-danger500 text-xs flex-1">
                          Invalid file format or size. Please upload a PNG, JPEG, or JPG file with the recommended size
                          of 128 × 128 px.
                        </p>
                      </div>
                    ) : (
                      <p className="text-xs text-neutral500">
                        Supported formats: PNG, JPEG, JPG (recommended size: 128 x 128 px).
                      </p>
                    )
                  ) : (
                    <p className="text-xs text-neutral500">
                      Supported formats: PNG, JPEG, JPG (recommended size: 128 x 128 px).
                    </p>
                  )}
                </div>
              </div>

              <input
                ref={inputLogoRef}
                type="file"
                accept="image/png, image/jpeg"
                className="hidden"
                onChange={handleLogoChange}
              />
            </>
          ) : !selectedLoyalty ? null : (
            <div className="flex flex-col">
              <img
                src={
                  typeof formik.values.logo === "string" ? formik.values.logo : URL.createObjectURL(formik.values.logo)
                }
                className="object-contain rounded-md border border-neutral80 cursor-pointer h-44"
              />
            </div>
          )}

          {editMode ? (
            <div className="col-span-4 flex flex-col gap-4">
              <TextInput
                title="PWA Name"
                isRequired={true}
                placeholder="Input PWA Name"
                value={formik.values.projectName}
                onChangeInput={(e) => {
                  let value = e.target.value;

                  // hanya izinkan huruf, angka, spasi, underscore, dan strip
                  value = value.replace(/[^a-zA-Z0-9 _-]/g, "");

                  // batasi panjang maksimal 30
                  value = value.slice(0, 30);

                  formik.setFieldValue("projectName", value);
                  formik.setFieldTouched("projectName", true, false);
                }}
                footer={
                  (formik.touched.projectName || formik.submitCount > 0) && formik.errors.projectName
                    ? formik.errors.projectName
                    : null
                }
                mode={
                  (formik.touched.projectName || formik.submitCount > 0) && formik.errors.projectName
                    ? "danger"
                    : "default"
                }
              />

              <TextArea
                title="Description"
                isRequired={false}
                placeholder="Input Description"
                value={formik.values.description}
                onChangeInput={(e) => {
                  formik.setFieldValue("description", e.target.value);
                  formik.setFieldTouched("description", true, false);
                }}
                footer={
                  (formik.touched.description || formik.submitCount > 0) && formik.errors.description
                    ? formik.errors.description
                    : null
                }
                mode={
                  (formik.touched.description || formik.submitCount > 0) && formik.errors.description
                    ? "danger"
                    : "default"
                }
              />

              <div>
                <div className="flex items-center mb-2">
                  <p className="font-semibold mr-2">Auto-Generated Landing Page URL</p>
                  <Switch
                    checked={formik.values.isAutoGenerated}
                    onChange={() => formik.setFieldValue("isAutoGenerated", !formik.values.isAutoGenerated)}
                    isEdit={true}
                  />
                </div>

                <div
                  className={`${
                    (formik.touched.landingPageURL || formik.submitCount > 0) && formik.errors.landingPageURL
                      ? "bg-danger50 border border-danger500 text-neutral300"
                      : "bg-primary50 text-primary500"
                  } p-2 rounded-md`}
                >
                  {formik.values.isAutoGenerated ? (
                    <div className="flex justify-between items-center">
                      <p className="break-all">{`https://my-prezent.sandeza.id/${formik.values.landingPageURL}`}</p>
                      {(formik.touched.landingPageURL || formik.submitCount > 0) && formik.errors.landingPageURL ? (
                        <Info size={20} className="text-danger500" />
                      ) : (
                        <button
                          type="button"
                          onClick={() =>
                            navigator.clipboard.writeText(
                              `https://my-prezent.sandeza.id/${formik.values.landingPageURL}`,
                            )
                          }
                          className="mt-1 px-2 self-start text-neutral500 hover:text-primary500"
                        >
                          <Copy size={20} weight="regular" />
                        </button>
                      )}
                    </div>
                  ) : (
                    <>
                      {formik.values.onFocus || !formik.values.landingPageURL ? (
                        <div className="flex justify-between items-center">
                          <div className="flex items-center border w-full">
                            <p className="whitespace-nowrap flex-shrink-0">{`https://my-prezent.sandeza.id/`}</p>
                            <input
                              autoFocus
                              value={formik.values.landingPageURL}
                              placeholder="program_name"
                              onFocus={() => formik.setFieldValue("onFocus", true)}
                              onBlur={() => {
                                if (formik.values.landingPageURL) {
                                  formik.setFieldValue("onFocus", false);
                                }
                              }}
                              onChange={(e) => {
                                let value = e.target.value;

                                // hanya izinkan huruf, angka, spasi, underscore, strip
                                value = value.replace(/[^a-zA-Z0-9 _-]/g, "");

                                // ubah ke lowercase
                                value = value.toLowerCase();

                                // ganti semua spasi jadi underscore
                                value = value.replace(/\s+/g, "_");

                                // rapikan underscore berlebih
                                value = value.replace(/_+/g, "_");

                                // batasi maksimal 30 karakter
                                value = value.slice(0, 30);

                                formik.setFieldValue("landingPageURL", value);
                                formik.setFieldTouched("landingPageURL", true, false);
                              }}
                              className={`${
                                (formik.touched.landingPageURL || formik.submitCount > 0) &&
                                formik.errors.landingPageURL
                                  ? "bg-danger50 text-neutral300 "
                                  : "bg-primary50 text-primary500"
                              } flex-1 min-w-0`}
                            />
                          </div>
                          {(formik.touched.landingPageURL || formik.submitCount > 0) && formik.errors.landingPageURL ? (
                            <Info size={20} className="text-danger500" />
                          ) : (
                            <button
                              type="button"
                              onClick={() =>
                                navigator.clipboard.writeText(
                                  `https://my-prezent.sandeza.id/${formik.values.landingPageURL}`,
                                )
                              }
                              className="mt-1 px-2 self-start text-neutral500 hover:text-primary500"
                            >
                              <Copy size={20} weight="regular" />
                            </button>
                          )}
                        </div>
                      ) : (
                        <div className="flex justify-between items-center">
                          <p onClick={() => formik.setFieldValue("onFocus", true)} className="cursor-pointer break-all">
                            {`https://my-prezent.sandeza.id/${formik.values.landingPageURL}`}
                          </p>
                          <button
                            type="button"
                            onClick={() =>
                              navigator.clipboard.writeText(
                                `https://my-prezent.sandeza.id/${formik.values.landingPageURL}`,
                              )
                            }
                            className="mt-1 px-2 self-start text-neutral500 hover:text-primary500"
                          >
                            <Copy size={20} weight="regular" />
                          </button>
                        </div>
                      )}
                    </>
                  )}
                </div>

                <div className="mt-2">
                  {(formik.touched.landingPageURL || formik.submitCount > 0) && formik.errors.landingPageURL && (
                    <div className="flex items-center text-sm">
                      <Info className="text-danger500 mr-2" size={16} />
                      <p className="text-danger500">{formik.errors.landingPageURL}</p>
                    </div>
                  )}
                  {formik.errors.landingPageURL !== "Please complete this required field to continue" && (
                    <p className={`text-neutral300 text-sm`}>
                      The landing page URL is generated automatically using the program name and can be used for
                      customer registration. Turn the toggle off to deactivate this feature.
                    </p>
                  )}
                </div>
              </div>
            </div>
          ) : !selectedLoyalty ? (
            <p className="text-neutral300 text-sm col-span-4">You haven’t configure this feature.</p>
          ) : (
            <div className="col-span-4 flex flex-col gap-4">
              <div className="text-sm flex-col gap-2">
                <p className="text-neutral300">PWA Name</p>
                <p className="font-medium">{formik.values.projectName}</p>
              </div>

              <div className="text-sm flex-col gap-2">
                <p className="text-neutral300">Descriptions</p>
                <p className="font-medium">{formik.values.description}</p>
              </div>

              <div className="text-sm flex-col gap-2">
                <p className="text-neutral300">Landing Page Url</p>
                <div className="p-2 flex justify-between items-center bg-neutral30 rounded-lg">
                  <p className="text-neutral700">https://my-prezent.sandeza.id/{formik.values.landingPageURL}</p>
                  <Copy
                    size={20}
                    weight="regular"
                    className="cursor-pointer"
                    onClick={() =>
                      navigator.clipboard.writeText(`https://my-prezent.sandeza.id/${formik.values.landingPageURL}`)
                    }
                  />
                </div>
              </div>
            </div>
          )}
        </div>

        <div className="border-t border-neutral30 flex items-center gap-4 justify-end py-3">
          {editMode ? (
            <>
              <DangerButton
                variant="outlined"
                title="Cancel"
                onClick={() => {
                  formik.resetForm();
                  toggleEdit();
                }}
              />
              <PrimaryButton title="Save" onClick={formik.handleSubmit} />
            </>
          ) : (
            <OutlineButton
              onClick={toggleEdit}
              title={
                <div className="flex items-center gap-1">
                  <NotePencil />
                  <p>Edit</p>
                </div>
              }
            />
          )}
        </div>
      </div>
    </div>
  );
};

export default PWASection;
