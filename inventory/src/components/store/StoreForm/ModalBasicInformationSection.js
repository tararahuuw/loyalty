import React from "react";
import { TextInput, Switch } from "sprint-asia-custom-component";
import { GenerateStore } from "../../../service/inventoryManagement/endpoint/store";
import ToolTip from "prezent/ToolTip";
import DropdownPhone from "prezent/DropdownPhone";

const ModalBasicInformationSection = ({ formik, clientName }) => {
  const corporateName = JSON.parse(localStorage.getItem("valueLogin"));
  async function generateStoreId() {
    try {
      var response = await GenerateStore({ name: corporateName.corporateName });
      return response.data;
    } catch (err) {
      return "STRSPR-00001";
    }
  }
  return (
    <div className="flex flex-col gap-3">
      <div className="text-lg font-semibold leading-6 text-left pb-2 border-b border-neutral40">Basic Information</div>

      <div className="grid grid-cols-3 gap-6 items-center">
        <div className="flex flex-col gap-5">
          <TextInput
            title="Store ID"
            placeholder="Store ID"
            onChangeInput={(e) => {
              formik.setFieldValue("code", e.target.value);
              formik.setFieldTouched("code", true, false);
            }}
            rightAdornment={
              <ToolTip
                message={
                  <div>
                    <p className="font-semibold">Format:</p>
                    <div className="flex items-center my-2">
                      <p className="mr-2 rounded-full px-4 py-1 font-semibold text-primary500 bg-primary100">STR</p>
                      <p className="mr-2 rounded-full px-4 py-1 font-semibold text-primary500 bg-primary100">
                        3 First Letter of Client Name
                      </p>
                      <p className="mr-2 rounded-full px-4 py-1 font-semibold text-primary500 bg-primary100">
                        5 Digit Running Number
                      </p>
                    </div>
                    <p className="font-semibold mt-4">Example:</p>
                    <div className="flex items-center my-2">
                      <p className="mr-2 rounded-full px-4 py-1 font-semibold text-success500 bg-success50">
                        STRSPR-00001
                      </p>
                    </div>
                  </div>
                }
              />
            }
            isRequired
            footer={(formik.touched.code || formik.submitCount > 0) && formik.errors.code ? formik.errors.code : null}
            mode={
              formik.values.isAutoGenerated
                ? "disable"
                : (formik.touched.code || formik.submitCount > 0) && formik.errors.code
                  ? "danger"
                  : "default"
            }
            value={formik.values.code}
            rightComponent={
              <div className="flex items-center mb-2 ml-4">
                <Switch
                  onChange={async () => {
                    const newValue = !formik.values.isAutoGenerated;
                    formik.setFieldValue("isAutoGenerated", newValue);

                    if (newValue) {
                      if (formik.values.storeCodeBucket === "") {
                        const storeId = await generateStoreId();
                        formik.setFieldValue("code", storeId);
                        formik.setFieldTouched("code", true, false);
                      } else {
                        formik.setFieldValue("code", formik.values.storeCodeBucket);
                        formik.setFieldTouched("code", true, false);
                      }
                    }
                  }}
                  checked={formik.values.isAutoGenerated}
                  isEdit
                />
                <p className={`ml-2 text-sm text-neutral50`}>Auto Generate</p>
              </div>
            }
          />
        </div>

        <div className="flex flex-col gap-5">
          <TextInput
            title="Store Name"
            placeholder="Input Name"
            onChangeInput={(e) => {
              formik.setFieldValue("name", e.target.value);
              formik.setFieldTouched("name", true, false);
            }}
            isRequired={true}
            footer={(formik.touched.name || formik.submitCount > 0) && formik.errors.name ? formik.errors.name : null}
            mode={(formik.touched.name || formik.submitCount > 0) && formik.errors.name ? "danger" : "default"}
            value={formik.values.name}
          />
        </div>
        <div className="flex flex-col gap-5">
          <DropdownPhone
            title="Store Phone Number"
            placeholder="Store Phone Number"
            dropdownCountry={formik.values.dropdownCountryStore}
            setDropdownCountry={(val) => {
              formik.setFieldValue("dropdownCountryStore", val);
            }}
            value={formik.values.phoneNumber}
            onChangeInput={(e) => {
              const onlyDigits = e.target.value.replace(/\D/g, "");
              formik.setFieldValue("phoneNumber", onlyDigits);
              formik.setFieldTouched("phoneNumber", true, false);
            }}
            footer={
              (formik.touched.phoneNumber || formik.submitCount > 0) && formik.errors.phoneNumber
                ? formik.errors.phoneNumber
                : null
            }
            mode={
              (formik.touched.phoneNumber || formik.submitCount > 0) && formik.errors.phoneNumber ? "danger" : "default"
            }
          />
        </div>
      </div>
    </div>
  );
};

export default ModalBasicInformationSection;
