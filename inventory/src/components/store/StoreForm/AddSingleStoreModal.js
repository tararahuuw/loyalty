import React, { useRef, Fragment, useState, useEffect } from "react";
import { Dialog, Transition } from "@headlessui/react";
import { X } from "@phosphor-icons/react";
import { ModalState, OutlineButton, PrimaryButton } from "sprint-asia-custom-component";
import StatusSection from "../../shared/StatusSection";
import ModalBasicInformationSection from "./ModalBasicInformationSection";
import AddressInformationSection from "./AddressInformationSection";
import { useFormik } from "formik";
import * as yup from "yup";
import { useFetch } from "prezent/useFetch";
import { useDisclosure } from "prezent/useDisclosure";
import {
  GetAllCity,
  GetAllDistrict,
  GetAllProvince,
  PostAllCity,
  PostAllDistrict,
} from "../../../service/inventoryManagement/endpoint/store";
import ConfirmationModal from "../../shared/ConfirmationModal";
import { parsePhoneNumberFromString } from "libphonenumber-js";
import { customList } from "country-codes-list";

const AddSingleStoreModal = ({
  isOpen,
  onClose,
  selectedStore,
  handleSubmitStore,
  clientName,
  setSelectedStore = () => {},
}) => {
  const cancelButtonRef = useRef(null);
  const [selectedProvince, setSelectedProvince] = useState(null);
  const [selectedCity, setSelectedCity] = useState(null);
  const { isOpen: confirmationModalIsOpen, toggle: toggleConfirmationModal } = useDisclosure(false);

  const handleToggleConfirmationModal = () => {
    onClose();
    toggleConfirmationModal();
  };

  const detectCountryFromPhone = (phoneNumber) => {
    if (!phoneNumber) return null;

    const phoneData = parsePhoneNumberFromString(phoneNumber);
    if (!phoneData || !phoneData.countryCallingCode || !phoneData.country) {
      return null;
    }

    const list = Object.entries(customList("countryCode", "{countryNameEn} +{countryCallingCode}")).map(
      ([code, label]) => {
        const [countryName, callingCode] = label.split(" +");
        return {
          option: `+${callingCode}`,
          value: code.toLowerCase(),
          label: countryName,
        };
      },
    );

    const match = list.find(
      (item) => item.option === `+${phoneData.countryCallingCode}` && item.value === phoneData.country.toLowerCase(),
    );

    return (
      match || {
        option: `+${phoneData.countryCallingCode}`,
        value: phoneData.country.toLowerCase(),
        label: phoneData.country || "Unknown",
      }
    );
  };

  const fullPhoneNumber = selectedStore?.phoneNumber || "";
  const detectedCountryStore = detectCountryFromPhone(fullPhoneNumber);
  const phoneNumber = fullPhoneNumber.replace(`+${detectedCountryStore?.option.replace("+", "")}`, "");

  const formik = useFormik({
    enableReinitialize: true,
    initialValues: {
      code: selectedStore?.code || "",
      name: selectedStore?.name || "",
      dropdownCountryStore: detectedCountryStore || {
        option: "+62",
        value: "id",
        label: "Indonesia",
      },
      phoneNumber: phoneNumber || "",
      province: selectedStore?.province || "",
      city: selectedStore?.city || "",
      district: selectedStore?.district || "",
      provinceCode: selectedStore?.provinceCode || "",
      cityCode: selectedStore?.cityCode || "",
      districtCode: selectedStore?.districtCode || "",
      address: selectedStore?.address || "",
      postalCode: selectedStore?.postalCode || "",
      status: selectedStore?.status === "Inactive" ? false : true,
      isAutoGenerated: selectedStore?.isAutoGenerated || false,
      storeCodeBucket: selectedStore?.isAutoGenerated ? selectedStore?.code : "",
    },
    validationSchema: yup.object().shape({
      code: yup
        .string()
        .matches(/^[a-zA-Z0-9_-]+$/, "Store ID can only contain alphanumeric")
        .min(5, "Enter the store ID with Min 5 & Max 50 characters.")
        .max(50, "Enter the store ID with Min 5 & Max 50 characters.")
        .required("Store ID is required"),
      name: yup
        .string()
        .matches(/^[^.,]+$/, "Store Name cannot contain commas (,) or period (.)")
        .min(3, "Enter the store name with Min 3 & Max 100 characters.")
        .max(100, "Enter the store name with Min 3 & Max 100 characters.")
        .required("Store Name is required"),
      phoneNumber: yup
        .string()
        .required("Phone Number is required")
        .min(8, "Phone Number is too short (min. 8 digit & max. 15 digit)")
        .max(15, "Phone number is too long (min. 8 digit & max. 15 digit)"),
      province: yup.string().required("Province is required"),
      city: yup.string().required("City is required"),
      district: yup.string().required("District is required"),
      address: yup
        .string()
        .trim()
        .max(255, "Enter the detail address with max 255 characters.")
        .required("Detail address is required"),
      postalCode: yup
        .string()
        .matches(/^\d+$/, "Postal Code must be numeric")
        .min(5, "Enter the postal code must be 5 digits.")
        .max(5, "Enter the postal code must be 5 digits.")
        .required("Postal Code is required"),

      status: yup.string().required("Status is required"),
    }),

    validateOnChange: true,
    validateOnBlur: true,
    onSubmit: (values, { resetForm }) => {
      const fullStoreNumber = `${formik.values.dropdownCountryStore.option}${formik.values.phoneNumber}`;

      const payload = {
        ...values,
        phoneNumber: fullStoreNumber,
      };

      handleSubmitStore(payload);
      setSelectedStore(null);
      resetForm();
      onClose();
    },
  });

  const { data: provinces } = useFetch(GetAllProvince, "provinces", [], {});
  const { data: cities } = useFetch(selectedProvince && PostAllCity, "cities", [], {
    province: [selectedProvince?.code],
  });
  const { data: districts } = useFetch(selectedCity && PostAllDistrict, "districts", [], {
    city: [selectedCity?.code],
  });

  useEffect(() => {
    if (provinces?.data?.length === 1) {
      formik.setFieldValue("province", provinces.data[0].name);
    }
  }, [provinces?.data?.length]);

  useEffect(() => {
    if (cities?.data?.length === 1) {
      formik.setFieldValue("city", cities.data[0].name);
    }
  }, [cities?.data?.length]);

  useEffect(() => {
    if (districts?.data?.length === 1) {
      formik.setFieldValue("district", districts.data[0].name);
    }
  }, [districts?.data?.length]);

  useEffect(() => {
    if (formik.values.province) {
      const selectedProvince = provinces?.data?.find(
        (province) => province.name.toLowerCase() === formik.values.province.toLowerCase(),
      );
      setSelectedProvince(selectedProvince);
    }
  }, [formik.values.province, provinces]);

  useEffect(() => {
    if (formik.values.city) {
      const selectedCity = cities?.data?.find((city) => city.name.toLowerCase() === formik.values.city.toLowerCase());
      setSelectedCity(selectedCity);
    }
  }, [formik.values.city, cities]);

  return (
    <>
      <Transition.Root show={isOpen} as={Fragment}>
        <Dialog
          as="div"
          className="fixed inset-0 overflow-y-auto"
          initialFocus={cancelButtonRef}
          onClose={() => {
            if (formik.dirty) {
              handleToggleConfirmationModal();
            } else {
              onClose();
              setSelectedStore(null);
              formik.resetForm();
            }
          }}
          static={false}
          style={{ zIndex: 1001 }}
        >
          <Transition.Child
            as={Fragment}
            enter="ease-out duration-300"
            enterFrom="opacity-0"
            enterTo="opacity-100"
            leave="ease-in duration-200"
            leaveFrom="opacity-100"
            leaveTo="opacity-0"
          >
            <div className="fixed inset-0 bg-black bg-opacity-25" onClick={(e) => e.stopPropagation()} />
          </Transition.Child>

          <Transition.Child
            as={Fragment}
            enter="ease-out duration-300"
            enterFrom="opacity-0 translate-y-4 sm:translate-y-0 sm:scale-95"
            enterTo="opacity-100 translate-y-0 sm:scale-100"
            leave="ease-in duration-200"
            leaveFrom="opacity-100 translate-y-0 sm:scale-100"
            leaveTo="opacity-0 translate-y-4 sm:translate-y-0 sm:scale-95"
          >
            <div className="min-h-screen flex items-center justify-center">
              <Dialog.Panel className="relative w-full max-w-6xl bg-white rounded-lg shadow-xl transition-all sm:my-8 sm:w-full sm:max-w-6xl py-3 flex flex-col gap-4">
                <div className="flex justify-between border-b border-neutral50 px-6 pb-2">
                  <p className="font-semibold text-xl text-black">{!selectedStore ? "Add Store" : "Edit Store"}</p>
                  <p
                    className="cursor-pointer text-xl"
                    onClick={() => {
                      if (formik.dirty) {
                        handleToggleConfirmationModal();
                      } else {
                        onClose();
                        setSelectedStore(null);
                        formik.resetForm();
                      }
                    }}
                  >
                    <X size={24} />
                  </p>
                </div>

                <div className="flex flex-col px-6 py-3 gap-10">
                  <ModalBasicInformationSection formik={formik} selectedStore={selectedStore} clientName={clientName} />

                  <AddressInformationSection
                    formik={formik}
                    cities={cities}
                    districts={districts}
                    provinces={provinces}
                    selectedStore={selectedStore}
                  />

                  <StatusSection
                    handleToggle={() => formik.setFieldValue("status", !formik.values.status)}
                    isChecked={formik.values.status}
                    itemName="Store"
                  />
                </div>

                <div className="flex gap-3 justify-end border-t border-neutral50 px-6 pt-3">
                  <OutlineButton
                    title="Cancel"
                    onClick={() => {
                      if (formik.dirty) {
                        handleToggleConfirmationModal();
                      } else {
                        formik.resetForm();
                        setSelectedStore(null);
                        onClose();
                      }
                    }}
                  />
                  <PrimaryButton title={"Submit"} onClick={formik.handleSubmit} />
                </div>
              </Dialog.Panel>
            </div>
          </Transition.Child>
        </Dialog>
      </Transition.Root>

      <ConfirmationModal
        isOpen={confirmationModalIsOpen}
        onClick={() => {
          toggleConfirmationModal();
          formik.resetForm();
          setSelectedStore(null);
        }}
        onClose={handleToggleConfirmationModal}
        subtitle="The information you filled in has not been saved and will be lost if you cancel this process."
        title="Do you want to cancel?"
      />
    </>
  );
};

export default AddSingleStoreModal;
