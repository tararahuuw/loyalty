import React from "react";
import { useState, useEffect } from "react";
import { TextInput } from "sprint-asia-custom-component";
import { PiTrash } from "react-icons/pi";
import GenerateModal from "./GenerateModal";
import { use } from "react";
import ToolTip from "prezent/ToolTip"

const SpecificationItem = ({
    formik,
}) => {

    const handleDeleteCombination = (indexToDelete) => {
        const updatedCombinations = formik.values.combinations.filter((_, i) => i !== indexToDelete);
        formik.setFieldValue("combinations", updatedCombinations);
    };

    useEffect(() => {
        if (formik.values.isAutoGenerated) {
            const updatedCombinations = formik.values.combinations.map((value, index) => ({
                ...value,
                sku: `${formik.values.masterSKU}${value.specificationsFirst ? `-${value.specificationsFirst.name.substring(0, 5)}` : ''}${value.specificationsSecond ? `-${value.specificationsSecond.name.substring(0, 5)}` : ''}`,
            }));
            formik.setFieldValue("combinations", updatedCombinations);
        }
    }, [formik.values.masterSKU, formik.values.specifications]);

    useEffect(() => {
        const updatedCombinations = formik.values.combinations.map(value => ({
            ...value,
            price: formik.values.priceMaster
        }));

        formik.setFieldValue("combinations", updatedCombinations);
    }, [formik.values.priceMaster]);

    return (
        <div className="mt-4">
            <div className="border-t border-dashed border-neutral50 mb-4"></div>

            <div className="border border-neutral50 rounded-lg shadow-sm">
                <div className="grid grid-cols-4 bg-white rounded-lg text-sm font-semibold px-4 py-2">
                    <div>
                        {
                            formik.values.specificationFirst.name
                        }
                    </div>
                    <div>
                        {
                            formik.values.specificationSecond.name
                        }
                    </div>
                    <div>
                        Price <span className="text-danger500">*</span>
                    </div>
                    <div>
                        SKU <span className="text-danger500">*</span>
                    </div>
                </div>

                <div className="grid grid-cols-4 gap-4 items-center rounded-md bg-neutral20 px-4 py-3 mx-4 mb-2 text-sm">
                    <p className="font-semibold col-span-2 text-right">
                        For apply to all
                    </p>
                    <TextInput
                        title={false}
                        placeholder="Input Price"
                        leftAdornment={<p className="text-xs pl-1">Rp</p>}
                        value={formik.values.priceMaster}
                        onChangeInput={(e) => {
                            formik.setFieldValue("priceMaster", e.target.value);
                            formik.setFieldTouched("priceMaster", true, false);
                        }}
                        type="number"
                        minimum={0}
                        footer={(formik.touched.priceMaster || formik.submitCount > 0) && formik.errors.priceMaster ? formik.errors.priceMaster : null}
                        mode={(formik.touched.priceMaster || formik.submitCount > 0) && formik.errors.priceMaster ? "danger" : "white"}
                        isRequired
                    />
                    <TextInput
                        title={false}
                        placeholder="Input SKU"
                        value={formik.values.masterSKU}
                        onChangeInput={(e) => {
                            const upperValue = e.target.value.replace(/\s+/g, "").toUpperCase();
                            formik.setFieldValue("masterSKU", upperValue);
                            formik.setFieldTouched("masterSKU", true, false);
                        }}
                        rightAdornment={
                            <ToolTip id={"masterSKU-specificationItem"} message={
                                <div>
                                    <p className="font-semibold">Format Auto Generate:</p>
                                    <div className="flex items-center my-2">
                                        <p className="mr-2 rounded-full px-4 py-1 font-semibold text-primary500 bg-primary100">PRD</p>
                                        <p className="mr-2 rounded-full px-4 py-1 font-semibold text-primary500 bg-primary100">3 First Letter of Client Name</p>
                                        <p className="mr-2 rounded-full px-4 py-1 font-semibold text-primary500 bg-primary100">5 Digit Running Number</p>
                                    </div>
                                    <p className="font-semibold mt-4">Example:</p>
                                    <div className="flex items-center my-2">
                                        <p className="mr-2 rounded-full px-4 py-1 font-semibold text-success500 bg-success50">PRDSPR-00001</p>
                                    </div>
                                </div>
                            } />
                        }
                        footer={(formik.touched.masterSKU || formik.submitCount > 0) && formik.errors.masterSKU ? formik.errors.masterSKU : null}
                        mode={formik.values.isAutoGenerated ? "disable" : (formik.touched.masterSKU || formik.submitCount > 0) && formik.errors.masterSKU ? "danger" : "white"}
                        isRequired
                    />
                </div>
                {formik.values.combinations.map((item, index) => {
                    return (
                        <div
                            key={index}
                            className="grid grid-cols-4 gap-4 bg-white text-sm px-4 py-2 items-center border-neutral30"
                        >
                            <p>{item.specificationsFirst?.name || "-"}</p>
                            <p>{item.specificationsSecond?.name || "-"}</p>
                            <div>
                                <TextInput
                                    title={false}
                                    placeholder="Input Price"
                                    leftAdornment={<p className="text-xs pl-1">Rp</p>}
                                    value={item.price}
                                    onChangeInput={(e) => {
                                        formik.setFieldValue(`combinations[${index}].price`, e.target.value);
                                    }}
                                    type="number"
                                    minimum={0}
                                    isRequired
                                    footer={(formik.submitCount > 0) && !formik.values.combinations?.[index]?.price ? "Input Price is required" : null}
                                    mode={(formik.submitCount > 0) && !formik.values.combinations?.[index]?.price
                                        ? "danger"
                                        : "white"
                                    }
                                />
                            </div>

                            <div className="flex items-center gap-2">
                                <TextInput
                                    placeholder="Input SKU"
                                    value={item.sku || ""}
                                    onChangeInput={(e) => {
                                        const value = e.target.value.replace(/\s+/g, "").toUpperCase(); // ❌ hapus spasi + kapitalin
                                        const updated = [...(formik.values.combinations || [])];
                                        updated[index] = {
                                            ...updated[index],
                                            sku: value,
                                        };
                                        formik.setFieldValue("combinations", updated);
                                    }}
                                    isRequired
                                    footer={(item.sku || formik.submitCount > 0) && !formik.values.combinations?.[index]?.sku ? "SKU is required" : null}
                                    mode={
                                        formik.values.isAutoGenerated
                                            ? "disable"
                                            : (item.sku || formik.submitCount > 0) && !formik.values.combinations?.[index]?.sku
                                                ? "danger"
                                                : "white"
                                    }
                                />
                                <PiTrash
                                    size={20}
                                    className="text-danger500 cursor-pointer"
                                    onClick={() => handleDeleteCombination(index)}
                                />
                            </div>
                        </div>
                    );
                })}

            </div>
        </div>
    );
};

export default SpecificationItem;
