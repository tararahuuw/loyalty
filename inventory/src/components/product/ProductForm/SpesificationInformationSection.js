import React, { useRef } from "react";
import { useState, useEffect } from "react";
import { DropdownText } from "sprint-asia-custom-component";
import SpecificationItem from "../../shared/SpesificationItem";
import { GetAllSpesification } from "../../../service/inventoryManagement/endpoint/product";
import { CaretDown, CaretUp, Trash } from "@phosphor-icons/react";
import MultiSelectDropdownText from "../../shared/MultiSelectDropdownText";
import MultiSelectDropdownNumber from "../../shared/MultiSelectDropdownNumber";

const SpesificationInformationSection = ({ formik, product }) => {
    const [dataFilterResult, setDataFilterResult] = useState({});
    const [isOpenSpecificationFirst, setIsOpenSpecificationFirst] = useState(false);
    const [isOpenSpecificationSecond, setIsOpenSpecificationSecond] = useState(false);
    function handleAddSpecification() {
        formik.setFieldValue("specifications", [...formik.values.specifications, { specificationsFirst: [], specificationsSecond: [] }])
    }

    function handleDeleteSpecifications(index) {
        if (formik.values.specifications.length > 1) {
            const newSpecifications = [...formik.values.specifications];
            newSpecifications.splice(index, 1);
            formik.setFieldValue("specifications", newSpecifications);
        }
    }

    const generateCombinations = (specifications, currentCombinations) => {
        const combinations = [];

        specifications.forEach((spec) => {
            const rawFirstSpecs = spec.specificationsFirst || [];
            const rawSecondSpecs = spec.specificationsSecond || [];

            const firstSpecs = rawFirstSpecs.flatMap((item) => {
                if (item.unit && item.unit !== "") {
                    return item.size.map((s) => ({
                        ...s,
                        parent: item,
                    }));
                }
                return [item];
            });

            const secondSpecs = rawSecondSpecs.flatMap((item) => {
                if (item.unit && item.unit !== "") {
                    return item.size.map((s) => ({
                        ...s,
                        parent: item,
                    }));
                }
                return [item];
            });

            const findMatchingCombo = (first, second) => {
                return currentCombinations?.find((combo) => {
                    const firstMatch = first && combo.specificationsFirst?.id === first.id;
                    const secondMatch = second && combo.specificationsSecond?.id === second.id;
                    return firstMatch && secondMatch;
                });
            };

            const buildCombo = (first, second, existing) => {
                const normalizeName = (str) => {
                    if (!str) return "";
                    return str.toUpperCase().replace(/\s+/g, "").substring(0, 5);
                };

                return {
                    ...(existing?.id ? { id: existing.id } : {}), // ✅ tambahin id hanya kalau ada
                    specificationsFirst: first,
                    specificationsSecond: second,
                    price: existing?.price || formik.values.priceMaster || "",
                    sku:
                        existing?.sku ||
                        (formik.values.isAutoGenerated
                            ? `${formik.values.masterSKU}${first?.name ? `-${normalizeName(first.name)}` : ""}${second?.name ? `-${normalizeName(second.name)}` : ""}`
                            : ""),
                };
            };

            if (firstSpecs.length && secondSpecs.length) {
                firstSpecs.forEach((first) => {
                    secondSpecs.forEach((second) => {
                        const existing = findMatchingCombo(first, second);
                        combinations.push(buildCombo(first, second, existing));
                    });
                });
            } else if (firstSpecs.length) {
                firstSpecs.forEach((first) => {
                    const existing = findMatchingCombo(first, null);
                    combinations.push(buildCombo(first, null, existing));
                });
            } else if (secondSpecs.length) {
                secondSpecs.forEach((second) => {
                    const existing = findMatchingCombo(null, second);
                    combinations.push(buildCombo(null, second, existing));
                });
            }
        });

        return combinations;
    };

    const dropdownRefFirst = useRef(null);
    const dropdownRefSecond = useRef(null);

    useEffect(() => {
        function handleClickOutside(event) {
            if (dropdownRefFirst.current && !dropdownRefFirst.current.contains(event.target)) {
                setIsOpenSpecificationFirst(false);
            }
            if (dropdownRefSecond.current && !dropdownRefSecond.current.contains(event.target)) {
                setIsOpenSpecificationSecond(false);
            }
        }

        document.addEventListener("mousedown", handleClickOutside);
        return () => {
            document.removeEventListener("mousedown", handleClickOutside);
        };
    }, []);

    useEffect(() => {
        var combinations = generateCombinations(formik.values.specifications, formik.values.combinations)
        formik.setFieldValue("combinations", combinations)
        formik.setFieldError("combinations", combinations)
    }, [formik.values.specifications])

    return (
        <div className="bg-white rounded-lg border border-neutral40 shadow-md p-6">
            <div className="text-lg font-semibold text-left pb-2">Spesifications</div>
            {!formik.values.category ? (
                <>
                    <div className="text-sm text-neutral500">
                        Available after selecting Product Category.
                    </div>
                    <hr className="text-neutral30 mt-2" />
                </>
            ) : (
                <>
                    <div>
                        <p className="text-neutral500 font-normal text-sm">
                            Turn on to allow different options for this product, such as size or color.
                        </p>
                    </div>

                    <div className="w-full mt-4">
                        <div className="w-full flex items-center">
                            <div ref={dropdownRefFirst} className="w-1/2 relative flex justify-between py-2 px-4 bg-neutral20 rounded-tl-lg border border-neutral30">
                                <p>{formik.values.specificationFirst.name}</p>
                                {
                                    isOpenSpecificationFirst ?
                                        <CaretUp size={20} className="text-neutral300 cursor-pointer" onClick={() => setIsOpenSpecificationFirst(!isOpenSpecificationFirst)} />
                                        :
                                        <CaretDown size={20} className="text-neutral300 cursor-pointer" onClick={() => setIsOpenSpecificationFirst(!isOpenSpecificationFirst)} />
                                }
                                {
                                    isOpenSpecificationFirst &&
                                    <div className="bg-white border border-neutral40 w-full rounded-md top-0 left-0 mt-10 absolute z-10 shadow-md">
                                        {
                                            formik.values.customSpecification
                                                .filter((value) => value.name !== "Brand" && value.name !== formik.values.specificationSecond?.name).map((value, index) =>
                                                    <div className="hover:bg-neutral20 p-2 rounded-md m-2" key={index} onClick={() => {
                                                        formik.setFieldValue("specificationFirst", value)
                                                        setIsOpenSpecificationFirst(false)
                                                    }}>
                                                        <p>{value.name}</p>
                                                    </div>
                                                )
                                        }
                                    </div>
                                }
                            </div>
                            <div ref={dropdownRefSecond} className="w-1/2 relative flex justify-between py-2 px-4 bg-neutral20 rounded-tr-lg border border-neutral30">
                                <p>{formik.values.specificationSecond.name}</p>
                                {
                                    isOpenSpecificationSecond ?
                                        <CaretUp size={20} className="text-neutral300 cursor-pointer" onClick={() => setIsOpenSpecificationSecond(!isOpenSpecificationSecond)} />
                                        :
                                        <CaretDown size={20} className="text-neutral300 cursor-pointer" onClick={() => setIsOpenSpecificationSecond(!isOpenSpecificationSecond)} />
                                }
                                {
                                    isOpenSpecificationSecond &&
                                    <div className="bg-white border border-neutral40 w-full rounded-md top-0 left-0 mt-10 absolute z-10 shadow-md">
                                        {
                                            formik.values.customSpecification
                                                .filter((value) => value.name !== "Brand" && value.name !== formik.values.specificationFirst?.name).map((value, index) =>
                                                    <div className="hover:bg-neutral20 p-2 rounded-md m-2" key={index} onClick={() => {
                                                        formik.setFieldValue("specificationSecond", value)
                                                        setIsOpenSpecificationSecond(false)
                                                    }}>
                                                        <p>{value.name}</p>
                                                    </div>
                                                )
                                        }
                                    </div>
                                }
                            </div>
                        </div>
                        {
                            formik.values.specifications.map((values, index) =>
                                <div className="w-full flex items-center">
                                    <div className="w-1/2 flex justify-between p-4 border border-neutral30 items-center">
                                        {
                                            formik.values.specificationFirst.type === "number" ?
                                                <MultiSelectDropdownNumber
                                                    options={
                                                        Array.isArray(formik.values?.specificationFirst?.specificationValues)
                                                            ? formik.values.specificationFirst.specificationValues.filter((option) => {
                                                                const selectedIds = formik.values.specifications
                                                                    .flatMap((spec, i) =>
                                                                        i !== index
                                                                            ? (spec.specificationsFirst || []).map((s) => s.id)
                                                                            : []
                                                                    );

                                                                return !selectedIds.includes(option.id);
                                                            })
                                                            : []
                                                    }
                                                    isRequired
                                                    title={null}
                                                    placeholder={`Select ${formik.values.specificationFirst.name}`}
                                                    setCurrentData={(value) => formik.setFieldValue(`specifications[${index}].specificationsFirst`, value)}
                                                    currentData={formik.values.specifications?.[index]?.specificationsFirst || []}
                                                />
                                                :
                                                <MultiSelectDropdownText
                                                    title={null}
                                                    placeholder={`Select ${formik.values.specificationFirst.name}`}
                                                    onChange={(value) => formik.setFieldValue(`specifications[${index}].specificationsFirst`, value)}
                                                    optionsData={
                                                        Array.isArray(formik.values?.specificationFirst?.specificationValues)
                                                            ? formik.values.specificationFirst.specificationValues.filter((option) => {
                                                                const selectedIds = formik.values.specifications
                                                                    .flatMap((spec, i) =>
                                                                        i !== index
                                                                            ? (spec.specificationsFirst || []).map((s) => s.id)
                                                                            : []
                                                                    );

                                                                return !selectedIds.includes(option.id);
                                                            })
                                                            : []
                                                    }
                                                    value={formik.values.specifications[index].specificationsFirst}
                                                />
                                        }
                                    </div>

                                    <div className="w-1/2 flex justify-between p-4 border border-neutral30 items-center">
                                        {
                                            formik.values.specificationSecond.type === "number" ?
                                                <MultiSelectDropdownNumber
                                                    options={formik.values?.specificationSecond?.specificationValues || []}
                                                    isRequired
                                                    title={null}
                                                    placeholder={`Select ${formik.values.specificationSecond.name}`}
                                                    setCurrentData={(value) => formik.setFieldValue(`specifications[${index}].specificationsSecond`, value)}
                                                    currentData={formik.values.specifications?.[index]?.specificationsSecond || []}
                                                />
                                                :
                                                <MultiSelectDropdownText
                                                    title={null}
                                                    placeholder={`Select ${formik.values.specificationSecond.name}`}
                                                    onChange={(value) => formik.setFieldValue(`specifications[${index}].specificationsSecond`, value)}
                                                    optionsData={formik.values?.specificationSecond?.specificationValues || []}
                                                    value={formik.values.specifications[index].specificationsSecond}
                                                />
                                        }

                                        <Trash size={20} className="ml-2 text-danger500 cursor-pointer" onClick={() => handleDeleteSpecifications(index)} />

                                    </div>
                                </div>
                            )
                        }
                        <div className="w-full flex items-center border border-neutral30 rounded-b-lg p-4">
                            <div className="w-full flex items-center justify-end">
                                {(() => {
                                    const selectedIds = formik.values.specifications
                                        .flatMap((spec) => (spec.specificationsFirst || []).map((s) => s.id));

                                    const availableOptions = formik.values.specificationFirst?.specificationValues?.filter(
                                        (option) => !selectedIds.includes(option.id)
                                    );

                                    const isAddable = availableOptions?.length > 0;

                                    return (
                                        <p
                                            className={`${isAddable ? "text-primary500 cursor-pointer" : "text-neutral80"}`}
                                            onClick={() => {
                                                if (isAddable) handleAddSpecification();
                                            }}
                                        >
                                            + Add Specification
                                        </p>
                                    );
                                })()}
                            </div>
                        </div>

                    </div>
                    <div>
                        <SpecificationItem
                            formik={formik}
                        />
                    </div>
                </>
            )}
        </div>
    );
};

export default SpesificationInformationSection;
