import React, { useEffect, useState } from "react";
import { useFormik } from "formik";
import * as yup from "yup";
import { useFetch } from "prezent/useFetch";
import { useDisclosure } from "prezent/useDisclosure";
import { GetAllClient } from "../../../service/inventoryManagement/endpoint/store";
import {
  CreateProduct,
  GetAllBrand,
  GetAllCategoryListTree,
  GetAllCustomSpecification,
  GetAllCustomSpecificationTable,
} from "../../../service/inventoryManagement/endpoint/product";
import { useNavigate } from "react-router-dom";
import { Footer } from "sprint-asia-custom-component";
import LoadingModal from "prezent/LoadingModal";
import ResultModal from "prezent/ResultModal";
import BasicInformationSection from "../../../components/product/ProductForm/BasicInformationSection";
import ProductInformationSection from "../../../components/product/ProductForm/ProductInformationSection";
import SpesificationInformationSection from "../../../components/product/ProductForm/SpesificationInformationSection";
import StatusSection from "../../../components/shared/StatusSection";
import StateModal from "prezent/StateModal";

const AddProduct = ({ roleAccess, setTitleHeader, userInfo }) => {
  const companyId = JSON.parse(localStorage.getItem("valueLogin"))?.corporateId;
  const navigate = useNavigate();
  const [flagResult, setFlagResult] = useState("success");
  const [dataSubtitleModal, setDataSubtitleModal] = useState("");
  const { isOpen: resultModalIsOpen, toggle: toggleResultModal } = useDisclosure(false);
  const { isOpen: loadingModalIsOpen, toggle: toggleLoadingModal } = useDisclosure(false);
  const { isOpen: confirmationModalIsOpen, toggle: toggleConfirmationModal } = useDisclosure(false);
  const { data: categories, isLoading: categoriesIsLoading } = useFetch(GetAllCategoryListTree, "categories", [], {});
  const { data: customSpecification } = useFetch(GetAllCustomSpecification, "specifications", [], { companyId });

  const handleOpenModalResult = (type, subtitle) => {
    setTimeout(() => {
      setFlagResult(type);
      setDataSubtitleModal(subtitle);
      toggleResultModal();
      setTimeout(() => {
        toggleResultModal();
      }, 3500);
    }, 250);
  };

  const submitNewProduct = async (form) => {
    try {
      toggleLoadingModal();
      const data = {
        ...form,
        priceMaster: Number(form.priceMaster),
        combinations:
          form.combinations?.map((c) => ({
            ...c,
            price: Number(c.price),
          })) || [],
      };
      await CreateProduct(roleAccess, data);

      toggleLoadingModal();
      setTimeout(() => {
        handleOpenModalResult("success", "Product has been successfully added");
        setTimeout(() => {
          navigate("/prezent/loyalty-setting/inventory/product");
        }, 4000);
      }, 250);
    } catch (error) {
      toggleLoadingModal();
      if (error?.response?.data?.rc === 409) {
        formik.setFieldError("productName", "Product Name can't be duplicate");
      } else {
        handleOpenModalResult("failed", "Sorry, unable to adding Product at the moment. Please try again");
      }
    }
  };

  const formik = useFormik({
    enableReinitialize: true,
    initialValues: {
      brand: "",
      brandId: "",
      category: "",
      companyId: companyId,
      isAutoGenerated: false,
      masterSKU: "",
      codeBucket: "",
      productName: "",
      priceMaster: "",
      customSpecification: customSpecification?.data || [],
      specificationFirst: Array.isArray(customSpecification?.data)
        ? customSpecification.data.find((item) => item.name === "Color") || []
        : [],

      specificationSecond: Array.isArray(customSpecification?.data)
        ? customSpecification.data.find((item) => item.name === "Size") || []
        : [],
      specifications: [
        {
          specificationsFirst: [],
          specificationsSecond: [],
        },
      ],
      status: true,
      combinations: [],
    },
    validationSchema: yup.object().shape({
      category: yup.mixed().test("is-valid-category", "Category is required", function (value) {
        if (value === "") return false;
        if (value == null) return false;
        if (typeof value === "object" && value.id) return true;
        return false;
      }),
      brandId: yup.string().required("Brand is required"),
      productName: yup.string().required("Products is required"),
      masterSKU: yup.string().required("Master SKU is required"),
    }),
    onSubmit: (values) => {
      if (isValidSpecifications(values.specifications) && isValidCombination(values.combinations)) {
        submitNewProduct(values);
      }
    },
    validateOnChange: true,
    validateOnBlur: true,
  });

  function isValidSpecifications(specifications) {
    if (!Array.isArray(specifications) || specifications.length < 1) {
      return false;
    }
    return specifications.some((spec) => {
      const hasFirst = Array.isArray(spec.specificationsFirst) && spec.specificationsFirst.length > 0;
      const hasSecond = Array.isArray(spec.specificationsSecond) && spec.specificationsSecond.length > 0;
      return hasFirst || hasSecond;
    });
  }

  function isValidCombination(combinations) {
    if (!Array.isArray(combinations)) return false;

    return combinations.every((item) => item.price !== "" && item.sku !== "");
  }

  const handleCancelButton = () => {
    toggleConfirmationModal();
  };

  useEffect(() => {
    setTitleHeader("Add Product");
  }, []);

  useEffect(() => {
    const updated = formik.values.specifications.map((item) => ({
      ...item,
      specificationsFirst: [], // reset
    }));

    formik.setFieldValue("specifications", updated);
  }, [formik.values.specificationFirst]);

  useEffect(() => {
    const updated = formik.values.specifications.map((item) => ({
      ...item,
      specificationsSecond: [], // reset
    }));

    formik.setFieldValue("specifications", updated);
  }, [formik.values.specificationSecond]);
  return (
    <div>
      <div className="bg-neutral20 pt-8 px-8 pb-4">
        <form className="flex flex-col gap-7">
          <BasicInformationSection
            formik={formik}
            categories={categories}
            brands={
              Array.isArray(formik.values.customSpecification)
                ? formik.values.customSpecification.find((item) => item.name === "Brand")?.specificationValues || []
                : []
            }
            clientName={userInfo.clientName}
          />
          <SpesificationInformationSection formik={formik} categories={categories} />

          <div className="flex flex-col gap-5 bg-white rounded-lg border border-neutral40 shadow-md p-6 mb-4">
            <StatusSection
              handleToggle={() => formik.setFieldValue("status", !formik.values.status)}
              isChecked={formik.values.status}
              itemName="Product"
            />
          </div>
        </form>
      </div>

      <Footer
        modeLeftButton="outline"
        modeRightButton="primary"
        titleLeftButton="Cancel"
        titleRightButton="Submit"
        isActiveLeftButton
        isActiveRightButton
        onClickLeftButton={handleCancelButton}
        onClickRightButton={formik.handleSubmit}
      />

      <LoadingModal
        title="Loading..."
        subtitle="Please wait a moment"
        isOpen={loadingModalIsOpen || categoriesIsLoading}
        onClose={() => {}}
      />

      <ResultModal subtitle={dataSubtitleModal} type={flagResult} isOpen={resultModalIsOpen} />

      <StateModal
        title="Do you want to cancel?"
        subtitle="The information you filled in has not been saved and will be lost if you cancel this process."
        isOpen={confirmationModalIsOpen}
        onClose={toggleConfirmationModal}
        type="default"
        titleButtonLeft="Back"
        titleButtonRight="Cancel"
        leftAction={toggleConfirmationModal}
        rightAction={() => navigate("/prezent/loyalty-setting/inventory/product")}
      />
    </div>
  );
};

export default AddProduct;
