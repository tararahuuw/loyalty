import React, { useState, useEffect } from "react";

import _ from "lodash";
import moment from "moment";

import { useNavigate, useParams } from "react-router-dom";
import { Footer, Description } from "sprint-asia-custom-component";
import LoadingModal from "prezent/LoadingModal";
import StateModal from "prezent/StateModal";
import ResultModal from "prezent/ResultModal";
import { useDisclosure } from "prezent/useDisclosure";
import { useFetch } from "prezent/useFetch";
import { PiTrash, PiNotePencil } from "react-icons/pi";
import { formatPrefixPhoneNumber } from "../../../utils/index";
import { DeleteStore, EditStore, GetStoreById } from "../../../service/inventoryManagement/endpoint/store";
import AddSingleStoreModal from "../../../components/store/StoreForm/AddSingleStoreModal";

const DetailStore = ({ roleAccess, setTitleHeader, loyaltyId, userInfo }) => {
  const { id } = useParams();
  const { isOpen: loadingModalIsOpen, toggle: toggleLoadingModal, close: closeLoadingModal } = useDisclosure(false);
  const { isOpen: deleteStoreModalIsOpen, toggle: toggleDeleteStoreModal } = useDisclosure(false);
  const { isOpen: editStoreModalIsOpen, toggle: toggleEditStoreModal } = useDisclosure(false);
  const { isOpen: resultModalIsOpen, open: openResultModal, close: closeResultModal } = useDisclosure(false);
  const { isOpen: storeListIsOpen, toggle: toggleStoreList } = useDisclosure(false);
  const { isOpen: isReRender, toggle: reRender } = useDisclosure(false);
  const { isOpen: clientModalIsOpen, open: openClientModal, close: closeClientModal } = useDisclosure(false);
  const { isOpen: sandezaIsOpen, open: openSandezaModal, close: closeSandezaModal } = useDisclosure(false);
  const { isOpen: confirmationIsOpen, toggle: toggleConfirmation } = useDisclosure(false);
  const { isOpen: deleteModalIsOpen, open: openDeleteModal, close: closeDeleteModal } = useDisclosure(false);
  const { isOpen: addBulkStoreIsOpen, toggle: toggleAddBulkStore, close: closeAddBulkStore } = useDisclosure(false);
  const { isOpen: addSingleStoreIsOpen, toggle: toggleSingleStore, close: closeSingleStore } = useDisclosure(false);
  const [flagResult, setFlagResult] = useState("success");
  const [dataSubtitleModal, setDataSubtitleModal] = useState("");
  const [isModalOpenResult, setIsModalOpenResult] = useState(false);
  const { data, isLoading } = useFetch(id && GetStoreById, "Store", [isReRender], { roleAccess, id });

  const navigateTo = useNavigate();

  function handleOpenModalResult(type, subtitle) {
    setTimeout(() => {
      setFlagResult(type);
      setDataSubtitleModal(subtitle);
      setIsModalOpenResult(true);
      setTimeout(() => {
        setIsModalOpenResult(false);
      }, 1000);
    }, 250);
  }

  function handleNavigateDashboardStore() {
    navigateTo("/prezent/loyalty-setting/inventory/store");
  }

  const handleOpenConfirmationModal = () => {
    toggleConfirmation();
    toggleStoreList();
  };

  const handleCloseConfirmationModal = () => {
    toggleConfirmation();
    toggleStoreList();
  };

  const handleConfirm = () => {
    toggleConfirmation();
    setSelectedMerchant(null);
    setSelectedClient(null);
  };

  const handleSubmitStore = async (form) => {
    try {
      var bodyRequest = {
        address: form?.address,
        city: form?.city,
        code: form?.code,
        district: form?.district,
        loyaltyId: loyaltyId,
        name: form?.name,
        phoneNumber: form?.phoneNumber,
        postalCode: form?.postalCode,
        province: form?.province,
        status: form?.status ? "Active" : "Inactive",
        isAutoGenerated: form?.isAutoGenerated,
      };
      await EditStore(roleAccess, id, bodyRequest);
      reRender();
      handleOpenModalResult("success", `Store has been successfully edited`);
    } catch (error) {
      if (error?.response?.data?.rc === 5) {
        handleOpenModalResult(
          "failed",
          `Sorry, we are unable to edit store at the moment. The store is currently being used for an active campaign.`
        );
      } else {
        handleOpenModalResult("failed", `Sorry, unable to edit store at the moment. Please try again`);
      }
    }
  };

  async function handleDeleteStore() {
    try {
      toggleLoadingModal();
      toggleDeleteStoreModal();
      await DeleteStore(roleAccess, id);
      toggleLoadingModal();
      setTimeout(() => {
        handleOpenModalResult("success", "Store has been successfully removed.");
        setTimeout(() => {
          handleNavigateDashboardStore();
        }, 1500);
      }, 250);
    } catch (error) {
      toggleLoadingModal();
      if (error?.response?.data?.rc === 5) {
        handleOpenModalResult(
          "failed",
          "Sorry, we are unable to delete store at the moment. The store is currently being used for an active campaign."
        );
      } else {
        handleOpenModalResult("failed", "Store has been failed deleted. Please try again");
      }
    }
  }

  useEffect(() => {
    setTitleHeader("Detail Store");
  }, []);

  return (
    <>
      <div className="flex-1 h-full overflow-y-auto bg-neutral20">
        <div className="py-6 px-8 mb-4">
          <div className="bg-white rounded-lg py-4 px-6 shadow-md mb-6">
            <p
              className={`py-2 font-semibold ${
                data?.data?.status.toLowerCase() === "inactive" ? "text-danger500" : "text-success500"
              }`}
            >{`Store ${data?.data.status.toLowerCase() === "active" ? "Active" : "Inactive"}`}</p>
            <div>
              <p className="text-black text-lg font-semibold">Basic Information</p>
              <div className="h-px bg-neutral30 mt-2 mb-2"></div>
              <div class="grid grid-cols-3 gap-4">
                <Description title="Store ID" value={data?.data?.code} />
                <Description title="Store Name" value={data?.data?.name} />
                <Description title="Store Phone Number" value={formatPrefixPhoneNumber(data?.data?.phoneNumber)} />
              </div>
            </div>
          </div>
          <div className="bg-white rounded-lg py-4 px-6 shadow-md mb-6">
            <div>
              <p className="text-black text-lg font-semibold">Address Information</p>
              <div className="h-px bg-neutral30 mt-2 mb-2"></div>
              <div class="grid grid-cols-3 gap-4">
                <Description title="Province" value={data?.data?.province} />
                <Description title="City" value={data?.data?.city} />
                <Description title="District" value={data?.data?.district} />
              </div>
              <div class="grid grid-cols-3 gap-4 mt-4">
                <div className="col-span-2">
                  <Description title="Detail Address" value={data?.data?.address} />
                </div>
                <Description title="Postal Code" value={data?.data?.postalCode} />
              </div>
            </div>
          </div>
          <div className="bg-white rounded-lg py-4 px-6 shadow-md">
            <div>
              <p className="text-black text-lg font-semibold">Detail Activity</p>
              <div className="h-px bg-neutral30 mt-2 mb-2"></div>
              <div class="grid grid-cols-3 gap-4">
                <div>
                  <Description title="Created By" value={data?.data?.createdByName} />
                  <p>{moment(data?.data.createdAt).format("DD MMM YYYY, HH.mm")}</p>
                </div>
                {(data?.data?.updatedByName || data?.data.updatedAt) && (
                  <div>
                    <Description title="Last Edited By" value={data?.data?.updatedByName || "-"} />
                    <p>{data?.data.updatedAt ? moment(data?.data.updatedAt).format("DD MMM YYYY, HH.mm") : "-"}</p>
                  </div>
                )}
              </div>
            </div>
          </div>
        </div>
        <Footer
          onClickLeftButton={toggleDeleteStoreModal}
          onClickRightButton={toggleSingleStore}
          titleLeftButton={
            <div className="flex items-center gap-2">
              <PiTrash />
              <p>Delete</p>
            </div>
          }
          titleRightButton={
            <div className="flex items-center gap-2">
              <PiNotePencil />
              <p>Edit</p>
            </div>
          }
          isActiveLeftButton
          isActiveRightButton
        />
        <LoadingModal
          title="Loading..."
          subtitle="Please wait a moment"
          isOpen={isLoading || loadingModalIsOpen}
          onClose={() => {}}
        />
        <ResultModal subtitle={dataSubtitleModal} type={flagResult} isOpen={isModalOpenResult} />
        <StateModal
          title="Confirm Deletion"
          subtitle={
            <p>
              Are you sure you want to delete the store: <span className="font-semibold">{data?.data?.name}</span>? This
              action cannot be undone.
            </p>
          }
          isOpen={deleteStoreModalIsOpen}
          onClose={toggleDeleteStoreModal}
          type="danger"
          titleButtonRight="Delete"
          leftAction={toggleDeleteStoreModal}
          rightAction={handleDeleteStore}
        />
        <StateModal
          title="Do you want to cancel?"
          subtitle="The information you filled in has not been saved and will be lost if you cancel this process."
          isOpen={confirmationIsOpen}
          onClose={handleCloseConfirmationModal}
          titleButtonLeft="Back"
          titleButtonRight="Cancel"
          leftAction={handleCloseConfirmationModal}
          rightAction={handleConfirm}
        />

        <AddSingleStoreModal
          isOpen={addSingleStoreIsOpen}
          onClose={toggleSingleStore}
          selectedStore={data?.data}
          roleAccess={roleAccess}
          handleSubmitStore={handleSubmitStore}
          clientName={userInfo.clientName}
        />
      </div>
    </>
  );
};

export default DetailStore;
